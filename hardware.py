def generate_mac_address():
    import random
    mac = [random.randint(0x00, 0xff) for _ in range(6)]
    # Set local bit and clear multicast bit
    mac[0] = (mac[0] & 0xfc) | 0x02
    return ':'.join(f'{b:02x}' for b in mac), ''.join(f'{b:02x}' for b in mac).upper()

