def fix_ios_headers(headers_dict, hw_dict=None):
    """
    Given a dict of headers generated by native anisette tools,
    overrides the generic parts with our hardware profile.
    """
    profile = hw_dict if hw_dict else HARDWARE_PROFILE
    if "X-Mme-Device-Id" in headers_dict:
        headers_dict["X-Mme-Device-Id"] = profile.get("hardware_uuid") or profile.get("uuid")
    if "X-Apple-I-SRL-NO" in headers_dict:
        headers_dict["X-Apple-I-SRL-NO"] = profile.get("serial_number")
    if "X-Apple-I-ROM" in headers_dict:
        headers_dict["X-Apple-I-ROM"] = profile.get("rom")
    if "X-MMe-Client-Info" in headers_dict:
        if hw_dict and "model" in hw_dict:
            headers_dict["X-MMe-Client-Info"] = f"<{hw_dict['model']}> <macOS;13.2.1;22D68> <com.apple.AuthKit/1 (com.apple.akd/1.0)>"
        else:
            headers_dict["X-MMe-Client-Info"] = CLIENT_INFO
    if "X-Apple-I-MLB" in headers_dict and hw_dict and "mlb" in hw_dict:
        headers_dict["X-Apple-I-MLB"] = hw_dict["mlb"]
    return headers_dict
